class LogMixin:
    """Миксин для логирования создания объектов"""

    def __init__(self, *args, **kwargs):
        """
        Логирование создания объекта

        Перехватывает все параметры и выводит их в консоль
        """
        # Получаем имя класса
        class_name = self.__class__.__name__

        # Получаем все параметры, переданные в конструктор
        # args - позиционные аргументы
        # kwargs - именованные аргументы

        # Формируем строку параметров
        params = []

        # Добавляем позиционные аргументы
        for arg in args:
            params.append(repr(arg))

        # Добавляем именованные аргументы
        for key, value in kwargs.items():
            params.append(f"{key}={repr(value)}")

        # Формируем строку вывода
        params_str = ", ".join(params)

        # Выводим информацию о создании объекта
        print(f"Создан объект: {class_name}({params_str})")

        # Вызываем следующий конструктор в цепочке наследования
        super().__init__(*args, **kwargs)
